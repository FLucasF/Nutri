-- -------------------------------------------------------- anotações em feed

CREATE TABLE patient_note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT        NOT NULL,
    patient_id BIGINT        NOT NULL,
    body       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP     NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(180),
    updated_by VARCHAR(180),
    CONSTRAINT fk_patient_note_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_patient_note_patient FOREIGN KEY (patient_id) REFERENCES patient (id)
);

CREATE INDEX ix_patient_note_patient ON patient_note (patient_id, created_at);
