-- Orientacoes nutricionais: os textos que o nutricionista entrega junto do plano.
--
-- Sao duas tabelas e nao uma porque servem a dois momentos diferentes. A
-- biblioteca guarda o texto que o consultorio reaproveita; a orientacao do
-- plano guarda o texto que um paciente especifico recebeu.
--
-- A copia entre as duas e deliberada. Se o plano apenas apontasse para a
-- biblioteca, corrigir um modelo mudaria em silencio o que dezenas de pacientes
-- ja receberam — inclusive planos encerrados, que sao registro do que foi
-- prescrito. E a mesma razao pela qual o item de refeicao grava o peso.

CREATE TABLE orientacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nulo identifica modelo do sistema, visivel a todos os consultorios.
    -- Preenchido, so o consultorio dono a enxerga. Mesmo eixo do acervo de
    -- alimentos e das medidas caseiras.
    conta_id       BIGINT,
    titulo         VARCHAR(150)  NOT NULL,
    corpo          VARCHAR(8000) NOT NULL,
    ativo          BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMP     NOT NULL,
    atualizado_em  TIMESTAMP,
    criado_por     VARCHAR(180),
    atualizado_por VARCHAR(180),
    CONSTRAINT fk_orientacao_conta FOREIGN KEY (conta_id) REFERENCES conta (id)
);

CREATE INDEX ix_orientacao_conta ON orientacao (conta_id);

CREATE TABLE orientacao_do_plano (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id       BIGINT        NOT NULL,
    -- Procedencia, nao dependencia: pode ficar nulo se o modelo de origem for
    -- removido, e o texto entregue continua intacto.
    orientacao_id  BIGINT,
    titulo         VARCHAR(150)  NOT NULL,
    corpo          VARCHAR(8000) NOT NULL,
    ordem          INTEGER       NOT NULL,
    criado_em      TIMESTAMP     NOT NULL,
    atualizado_em  TIMESTAMP,
    criado_por     VARCHAR(180),
    atualizado_por VARCHAR(180),
    CONSTRAINT fk_orientacao_plano_plano FOREIGN KEY (plano_id)
        REFERENCES plano_alimentar (id),
    CONSTRAINT fk_orientacao_plano_origem FOREIGN KEY (orientacao_id)
        REFERENCES orientacao (id)
);

CREATE INDEX ix_orientacao_plano ON orientacao_do_plano (plano_id);

