-- Questionários pré-consulta.
--
-- O paciente responde por link, sem conta — o mesmo mecanismo pelo qual ele lê
-- o plano. É recurso de tempo do nutricionista, e não de engajamento do
-- paciente: chegar à consulta com a leitura feita é o que ele compra aqui.
--
-- Duas redundâncias deliberadas sustentam o modelo, e as duas existem porque
-- uma resposta é o registro de uma consulta que aconteceu numa data:
--
--   1. A resposta guarda o enunciado da pergunta, e não só a chave dela. Se o
--      nutricionista remover uma pergunta do modelo depois, a resposta antiga
--      não pode perder o enunciado — o paciente respondeu àquela pergunta.
--   2. A resposta guarda a versão do modelo que foi aplicada. É o que permite
--      saber qual formulário o paciente viu, sem reconstruí-lo.
--
-- Sobre instrumentos validados: o sistema traz um modelo genérico de
-- pré-consulta, de autoria própria. Instrumentos publicados — rastreamento
-- metabólico, FINDRISC, escalas de sono — têm licença própria, e cabe a cada
-- consultório cadastrar os que tem direito de usar.

CREATE TABLE questionario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nulo identifica modelo do sistema, comum a todos os consultórios.
    conta_id       BIGINT,
    nome           VARCHAR(150) NOT NULL,
    descricao      VARCHAR(1000),
    -- Nome do instrumento publicado, quando o questionário for um deles.
    instrumento    VARCHAR(120),
    versao         VARCHAR(30),
    pontuavel      BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Faixas de corte, no formato "0-5=Baixo|6-10=Moderado|11-99=Alto".
    faixa_de_corte VARCHAR(500),
    -- Incrementa a cada edição. A resposta guarda o número que respondeu.
    versao_modelo  INTEGER      NOT NULL DEFAULT 1,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMP    NOT NULL,
    atualizado_em  TIMESTAMP,
    criado_por     VARCHAR(180),
    atualizado_por VARCHAR(180),
    CONSTRAINT fk_questionario_conta FOREIGN KEY (conta_id) REFERENCES conta (id)
);

CREATE INDEX ix_questionario_conta ON questionario (conta_id);

CREATE TABLE pergunta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    questionario_id  BIGINT       NOT NULL,
    enunciado        VARCHAR(500) NOT NULL,
    -- TEXTO | NUMERO | ESCOLHA_UNICA | MULTIPLA
    tipo             VARCHAR(20)  NOT NULL,
    obrigatoria      BOOLEAN      NOT NULL DEFAULT FALSE,
    ordem            INTEGER      NOT NULL,
    -- Opções no formato "Nunca=0|Às vezes=1|Sempre=2". O número depois do sinal
    -- é a pontuação, e fica ausente quando o questionário não pontua.
    opcoes           VARCHAR(2000),
    ajuda            VARCHAR(500),
    criado_em        TIMESTAMP    NOT NULL,
    atualizado_em    TIMESTAMP,
    criado_por       VARCHAR(180),
    atualizado_por   VARCHAR(180),
    CONSTRAINT fk_pergunta_questionario FOREIGN KEY (questionario_id)
        REFERENCES questionario (id)
);

CREATE INDEX ix_pergunta_questionario ON pergunta (questionario_id);

CREATE TABLE resposta_questionario (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id              BIGINT       NOT NULL,
    paciente_id           BIGINT       NOT NULL,
    agendamento_id        BIGINT,
    questionario_id       BIGINT       NOT NULL,
    -- A versão do modelo que o paciente viu.
    versao_modelo         INTEGER      NOT NULL,
    -- Endereço do formulário, como o identificador do plano público.
    identificador_publico VARCHAR(36)  NOT NULL,
    enviado_em            TIMESTAMP    NOT NULL,
    respondido_em         TIMESTAMP,
    escore                INTEGER,
    classificacao         VARCHAR(120),
    -- A regra de corte usada, congelada na resposta.
    faixa_de_corte        VARCHAR(500),
    criado_em             TIMESTAMP    NOT NULL,
    atualizado_em         TIMESTAMP,
    criado_por            VARCHAR(180),
    atualizado_por        VARCHAR(180),
    CONSTRAINT fk_resposta_conta         FOREIGN KEY (conta_id)        REFERENCES conta (id),
    CONSTRAINT fk_resposta_paciente      FOREIGN KEY (paciente_id)     REFERENCES paciente (id),
    CONSTRAINT fk_resposta_agendamento   FOREIGN KEY (agendamento_id)  REFERENCES agendamento (id),
    CONSTRAINT fk_resposta_questionario  FOREIGN KEY (questionario_id) REFERENCES questionario (id),
    CONSTRAINT uk_resposta_publica UNIQUE (identificador_publico)
);

CREATE INDEX ix_resposta_paciente ON resposta_questionario (paciente_id);
CREATE INDEX ix_resposta_publica  ON resposta_questionario (identificador_publico);

CREATE TABLE resposta_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resposta_id     BIGINT       NOT NULL,
    pergunta_id     BIGINT,
    -- Congelado no envio: a pergunta pode sair do modelo depois.
    pergunta_texto  VARCHAR(500) NOT NULL,
    valor           VARCHAR(2000),
    pontos          INTEGER,
    ordem           INTEGER      NOT NULL,
    criado_em       TIMESTAMP    NOT NULL,
    atualizado_em   TIMESTAMP,
    criado_por      VARCHAR(180),
    atualizado_por  VARCHAR(180),
    CONSTRAINT fk_item_resposta FOREIGN KEY (resposta_id) REFERENCES resposta_questionario (id)
);

CREATE INDEX ix_item_resposta ON resposta_item (resposta_id);

