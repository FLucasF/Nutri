INSERT INTO pergunta (questionario_id, enunciado, tipo, obrigatoria, ordem, opcoes, ajuda, criado_em)
SELECT q.id, p.enunciado, p.tipo, p.obrigatoria, p.ordem, p.opcoes, p.ajuda, CURRENT_TIMESTAMP
FROM questionario q
JOIN (
    SELECT 'O que você espera do acompanhamento nutricional?' AS enunciado,
           'TEXTO' AS tipo, TRUE AS obrigatoria, 1 AS ordem,
           CAST(NULL AS VARCHAR(2000)) AS opcoes,
           CAST('Escreva com suas palavras.' AS VARCHAR(500)) AS ajuda
    UNION ALL SELECT 'Você tem alguma condição de saúde diagnosticada?', 'TEXTO', FALSE, 2,
           NULL, 'Diabetes, hipertensão, tireoide, doença celíaca, outras.'
    UNION ALL SELECT 'Faz uso de medicamento ou suplemento?', 'TEXTO', FALSE, 3,
           NULL, 'Inclua a dose, se souber.'
    UNION ALL SELECT 'Tem alergia ou intolerância alimentar?', 'TEXTO', FALSE, 4, NULL, NULL
    UNION ALL SELECT 'Quantas refeições você faz por dia?', 'ESCOLHA_UNICA', TRUE, 5,
           'Uma ou duas|Três|Quatro ou cinco|Mais de cinco', NULL
    UNION ALL SELECT 'Com que frequência come fora de casa?', 'ESCOLHA_UNICA', FALSE, 6,
           'Raramente|Uma ou duas vezes por semana|Quase todo dia|Todo dia', NULL
    UNION ALL SELECT 'Quantos litros de água você bebe por dia?', 'NUMERO', FALSE, 7, NULL, NULL
    UNION ALL SELECT 'Pratica atividade física?', 'ESCOLHA_UNICA', FALSE, 8,
           'Não pratico|Uma a duas vezes por semana|Três a quatro vezes|Cinco ou mais', NULL
    UNION ALL SELECT 'Quantas horas você dorme por noite?', 'NUMERO', FALSE, 9, NULL, NULL
    UNION ALL SELECT 'Há algo que você gostaria que eu soubesse antes da consulta?', 'TEXTO',
           FALSE, 10, NULL, NULL
) p ON TRUE
WHERE q.conta_id IS NULL AND q.nome = 'Pré-consulta';
