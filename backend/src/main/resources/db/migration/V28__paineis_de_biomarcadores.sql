-- Painéis de biomarcadores, das páginas 6 a 13 do documento do cliente.
--
-- Ele descreve botões que preenchem o bloco de texto do pedido: "ao
-- clicarmos em algum desses botões, será preenchido na direita os marcadores
-- ligados ao botão". Um painel é esse botão — um conjunto nomeado de
-- parâmetros.
--
-- São 25 painéis e 154 parâmetros distintos, extraídos do próprio PDF e não
-- digitados: a lista é longa o bastante para que a digitação errasse mais do
-- que a leitura.
--
-- Sobre a unidade: a lista dele não traz nenhuma, e inventar 124 unidades de
-- exame seria o tipo de chute que troca mg/dL por µg/dL num laudo. A coluna
-- passa a aceitar nulo, o que também é o modelo certo: um parâmetro que se
-- pede não precisa de unidade; um resultado que se registra precisa, e esse
-- já a tem em labtest.unit.
--
-- Só usa o subconjunto comum a H2 e PostgreSQL (AD-11).

ALTER TABLE labtest_parameter ALTER COLUMN standard_unit DROP NOT NULL;

CREATE TABLE labtest_panel (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nulo identifica painel do sistema, comum a todos os consultórios.
    account_id BIGINT,
    name       VARCHAR(150) NOT NULL,
    sort_order INTEGER      NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(180),
    updated_by VARCHAR(180),
    CONSTRAINT fk_labtest_panel_account FOREIGN KEY (account_id) REFERENCES account (id)
);

CREATE INDEX ix_labtest_panel_account ON labtest_panel (account_id);

CREATE TABLE labtest_panel_parameter (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    panel_id     BIGINT  NOT NULL,
    parameter_id BIGINT  NOT NULL,
    sort_order   INTEGER NOT NULL,
    created_at   TIMESTAMP NOT NULL,
    updated_at   TIMESTAMP,
    created_by   VARCHAR(180),
    updated_by   VARCHAR(180),
    CONSTRAINT fk_panel_parameter_panel FOREIGN KEY (panel_id)
        REFERENCES labtest_panel (id),
    CONSTRAINT fk_panel_parameter_parameter FOREIGN KEY (parameter_id)
        REFERENCES labtest_parameter (id),
    CONSTRAINT uk_panel_parameter UNIQUE (panel_id, parameter_id)
);

CREATE INDEX ix_panel_parameter_panel ON labtest_panel_parameter (panel_id);

